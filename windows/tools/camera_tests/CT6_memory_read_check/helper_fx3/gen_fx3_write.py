"""Write the headers the A7 IV helper (helper/readcheck.c) needs to carry the FX3 7.02 designs.

  work/venv/Scripts/python.exe -I -B gen_fx3_write.py

The FX3 counterpart of helper_s3/gen_s3_write.py (the A7S III kit, which ran on an A7S III), made from it by fixed replacements on
2026-11-24: the FX3 7.02 files, its table addresses and the four FX3 designs. The checks are the A7S III generator's.

The write levels of readcheck.c are used as they are (levels 5/6, 16/17, 19/20: the code that ran on the A7 IV);
only their tables differ. This writes, into helper/, in the formats helper/gen_expected.py writes:
  expected_sites_ogsq_fx3_v1.h            levels 5 and 6: the sensor sites and the changed bytes of the stored record
  expected_words_outsz2560_fx3_v1.h       levels 16 and 17: the output-size word and its two guards
  expected_mp_ogfile2560_hs_s_fx3_v1.h    levels 19 and 20 (and 18): the encoder-side sites and guards
and for the rear screen, built as separate libraries (S16, S17):
  expected_words_lcd32dsq_fx3_v1.h        levels 16 and 17: the 3:2 ratio, the frame-table entries and the de-squeeze words, with their guards
and since 2026-11-25:
  expected_ad_avdec8k_fx3_v1.h            levels 29 and 30: the playback decoder (av-cam code and data)
  expected_mp_ogfilesi2560_fx3_v1.h       levels 19 and 20 again (I19 / I20): XAVC S-I 4K at 3840x2560 (build/build_ogfile_si.py --build fx3_702)
and since 2026-11-26 (open gate at 25p and 29.97p as well):
  expected_sites_ogsq_fx3_v2.h            levels 5 and 6: v1's cells, the same cells on drive mode 0x820, and the stored records of 0x820 and 0x8c0
                                          in their NTSC and PAL forms (readcheck.c MULTI_REC, as the FX30 kit; build/build_og_fx3_v2.py)
  expected_mp_ogfile2560_hs_s_fx3_v3.h    levels 19 and 20 (L19 / L20): v2 + the 29.97p descriptors (build/build_ogfile.py --build fx3_702 --meta --rate30)
  expected_mp_ogfilesi2560_fx3_v2.h       levels 19 and 20 (I19 / I20): S-I v1 + the 29.97p descriptors (build/build_ogfile_si.py --build fx3_702 --rate30)
and since 2026-11-28, the 4224 x 2816 state (modding/FX3_PORT.md; the A7S III's, modding/A7S3_PORT.md section 32), built as separate libraries:
  expected_sites_ogh2816_fx3_v1.h         levels 5 and 6 (H5 / H6): v2's cells, the two records with the first stage passed one to one, the four stored
                                          records with the ratio 27/32
  expected_words_dmm7slot_fx3_v1.h        levels 16 and 17 (D16 / D17): the output planes (ten words of the run-time copy of DmmCfg.bin's unit records)
  expected_words_outsz4224_fx3_v1.h       levels 16 and 17 (K16 / K17): the output-size word, 4224 x 2816
  expected_mp_ogfile4224_fx3_v1.h         levels 19 and 20 (K19 / K20): the encoder side at 4224 x 2816 with the MP4 header size
  expected_mp_ogfile4224nm_fx3_v1.h       level 19 (J19): the same without the MP4 header size (K20 puts it back)
  expected_mp_ogfile4224r300_fx3_v1.h     levels 19 and 20 (R19 / R20): as K19, the 100M settings at 300 Mbps
The FX3 kit has no preview-key routine: the camera's own Anamorphic Desqueeze is kept. Every stock byte is compared with the 7.02 files here. gen_expected.py is not used: its checks name A7 IV
addresses. The same kinds of check are made below with this build's.
"""
import hashlib
import json
import struct
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "helper"
ROOT = HERE.parents[2]
EX = ROOT / "work/extracted/fx3_702/0700_part_image/dev"
DES = ROOT / "modding/designs"
BASE = 0x108000
IMAGE_END = 0x108000 + 15980568
DATA_LO = 0xAEA000                                    # the FX3's constant data starts near 0xaea720 (the A7S III's 0xb11000 page)
SIZE_TABLE = (0x13C3190, 0x13C3190 + 0x80)             # the movie size table (build/emu_size_table.py fx3_702)
DESC, UNIT, CLIP, COMB = 0x395108, 0x395068, 0x39335C, 0x2CB108     # the A7S III's + 0x77a0 (clip + 0x7780), libmpr - 0x9300
hx = lambda b: ", ".join("0x%02x" % x for x in b)


def sites_header(name="ogsq_fx3_v1"):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    image = (EX / "nflasha8/cpapp-b.bin").read_bytes()
    assert d["artifact_sha256"] == hashlib.sha256(image).hexdigest() and d["mode_id"] == "0x8c0"
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    out = [f"/* Generated by helper_fx3/gen_fx3_write.py from modding/designs/{name}.json (FX3 7.02). Do not edit. */",
           "/* %d sites, %d bytes. Stock bytes were compared with cpapp-b.bin %s. */" % (len(sites), sum(len(o) for _, o, _ in sites), d["artifact_sha256"][:16])]
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and image[a - BASE:a - BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and DATA_LO <= lo and hi <= IMAGE_END, "span outside the image's constant or initialised data"
        for tag, data in (("old", old), ("new", new)):
            out.append("static const u8 site%d_%s[%d] = { %s };" % (k, tag, len(data), hx(data)))
        rows.append("    { 0x%x, %d, site%d_old, site%d_new, 0, 0 }," % (a, len(old), k, k))
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"
    sr = d["stored_record"]
    r_stock, r_new = bytes.fromhex(sr["stock"]), bytes.fromhex(sr["design"])
    offs = [k for k in range(0x15C) if r_stock[k] != r_new[k]]
    assert len(r_stock) == len(r_new) == 0x15C and offs[:2] == [6, 7] and r_stock[6] == r_stock[7] == 1 and 2 < len(offs) <= 128
    out += ["static const unsigned short rec_offs[%d] = { %s };" % (len(offs), ", ".join("0x%x" % k for k in offs)),
            "static const u8 rec_stock[%d] = { %s };" % (len(offs), hx(bytes(r_stock[k] for k in offs))),
            "static const u8 rec_new[%d] = { %s };" % (len(offs), hx(bytes(r_new[k] for k in offs))),
            "#define REC_BYTES %d" % len(offs),
            '#define SITES_TEXT "%d"' % len(sites), '#define ALL_TEXT "%d"' % (len(sites) + 1),
            "/* offs: null for a site whose `length` bytes all change; else the offsets, inside `length` bytes, of the noffs bytes that change. */",
            "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
            "static const struct cp_site cp_sites[] = {"] + rows + ["};"]
    (OUT / f"expected_sites_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(offs)


def sites_header_multi(name="ogsq_fx3_v2", ratio=(16, 19), records_of_v1=True):
    """Levels 5 and 6 for a design with more than one drive mode (2026-11-26): the cells and the record pair as sites_header(), then the stored
    records of every mode in the design, each in its NTSC and PAL form, in the format helper_fx30/gen_fx30_write.py writes (MULTI_REC)."""
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    image = (EX / "nflasha8/cpapp-b.bin").read_bytes()
    assert d["artifact_sha256"] == hashlib.sha256(image).hexdigest() and d["record_size"] == 0x15C
    sites = sorted((int(p["addr"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])) for p in d["patches"])
    v1 = {(int(p["addr"], 16), p["old"], p["new"]) for p in json.loads((DES / "ogsq_fx3_v1.json").read_text(encoding="utf8"))["patches"]
          if records_of_v1 or p["kind"] != "R"}          # ogh2816_fx3_v1 (the 4224x2816 state): v1's cells, other bytes in the two records
    assert v1 <= {(a, o.hex(), n.hex()) for a, o, n in sites}, "v1's sites are not all in the design"
    out = [f"/* Generated by helper_fx3/gen_fx3_write.py from modding/designs/{name}.json (FX3 7.02). Do not edit. */",
           "/* %d sites, %d bytes, and the stored records of %s. Stock bytes were compared with cpapp-b.bin %s. */"
           % (len(sites), sum(len(o) for _, o, _ in sites), ", ".join(d["mode_ids"]), d["artifact_sha256"][:16])]
    rows = []
    for k, (a, old, new) in enumerate(sites):
        assert len(old) == len(new) and old != new and image[a - BASE:a - BASE + len(old)] == old
        lo, hi = a & ~63, (a + len(old) + 63) & ~63
        assert hi - lo <= 4096 and DATA_LO <= lo and hi <= IMAGE_END, "span outside the image's constant or initialised data"
        for tag, data in (("old", old), ("new", new)):
            out.append("static const u8 site%d_%s[%d] = { %s };" % (k, tag, len(data), hx(data)))
        rows.append("    { 0x%x, %d, site%d_old, site%d_new, 0, 0 }," % (a, len(old), k, k))
    assert all(a + len(o) <= b for (a, o, _), (b, _, _) in zip(sites, sites[1:])), "sites overlap"
    modes = sorted(int(m, 16) for m in d["stored_records"])
    assert [hex(m) for m in modes] == d["mode_ids"]
    offs, stock, new = None, [], []
    for m in modes:
        sr = d["stored_records"][hex(m)]
        o = [int(x, 16) for x in sr["offsets_that_differ"]]
        assert offs is None or o == offs, "the modes' record sites differ"
        offs = o
        st_m, nw_m = [], []
        for v in ("ntsc", "pal"):
            s, n = bytes.fromhex(sr[v]["stock"]), bytes.fromhex(sr[v]["design"])
            assert len(s) == len(n) == 0x15C and s[6] == s[7] == 1 and n[6:8] == bytes(ratio)
            assert all(s[k] == n[k] for k in range(0x15C) if k not in o), "a changed byte outside the site list"
            st_m.append(bytes(s[k] for k in o))
            nw_m.append(bytes(n[k] for k in o))
        assert len({st_m[0], st_m[1], nw_m[0], nw_m[1]}) == 4, "a variant's bytes equal another's: the variant could not be told"
        stock.append(st_m)
        new.append(nw_m)
    assert offs[:2] == [6, 7] and 2 < len(offs) <= 128
    arr = lambda t: "{ " + ", ".join("{ " + ", ".join("{ %s }" % hx(v) for v in m) + " }" for m in t) + " }"
    out += ["#define MULTI_REC 1",
            "#define N_RECS %d" % len(modes), "#define REC_VARIANTS 2",
            '#define REC_VARIANTS_TEXT "NTSC 60 Hz or PAL 50 Hz"',
            "#define REC_BYTES %d" % len(offs),
            "static const u32 rec_modes[N_RECS] = { %s };" % ", ".join("0x%x" % m for m in modes),
            "static const char *const rec_mode_text[N_RECS] = { %s };" % ", ".join('"%#x"' % m for m in modes),
            'static const char *const rec_variant_name[REC_VARIANTS] = { "NTSC (60 Hz)", "PAL (50 Hz)" };',
            "static const unsigned short rec_offs[REC_BYTES] = { %s };" % ", ".join("0x%x" % k for k in offs),
            "/* per mode (rec_modes order), per variant (NTSC, PAL): the bytes at rec_offs before and after */",
            "static const u8 rec_stock[N_RECS][REC_VARIANTS][REC_BYTES] = %s;" % arr(stock),
            "static const u8 rec_new[N_RECS][REC_VARIANTS][REC_BYTES] = %s;" % arr(new),
            '#define SITES_TEXT "%d"' % len(sites), '#define ALL_TEXT "%d"' % (len(sites) + len(modes)),
            "/* offs: null for a site whose `length` bytes all change; else the offsets, inside `length` bytes, of the noffs bytes that change. */",
            "struct cp_site { u64 address; u32 length; const u8 *stock; const u8 *changed; const unsigned short *offs; u32 noffs; };",
            "static const struct cp_site cp_sites[] = {"] + rows + ["};"]
    (OUT / f"expected_sites_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(offs), [hex(m) for m in modes]


# Where a words design may have a site, and where a guard (the site regions plus these). The rear-screen design: the VDF fit-mode tables
# after the fit function (a guard may cover the function too) and the three frame-table rows (build/build_lcd_s3.py).
DMM_UNITS = (0x1F7F90C, 0x1F7F90C + 0x14 * 1205)     # the run-time copy of DmmCfg.bin's unit records (build/parse_dmmcfg.py RAM fx3_702; 1,205 records
#                                                      with the end markers: every byte of a dmm design is checked against the file below)
WORD_REGIONS = {"outsz2560_fx3_v1": ((SIZE_TABLE,), ()),
                "outsz4224_fx3_v1": ((SIZE_TABLE,), ()),
                "dmm7slot_fx3_v1": ((DMM_UNITS,), ()),
                # the picture-ratio function's 16:9 constants, the de-squeeze calculator's ratio words, the two compares of the 2.0x crop and the
                # three frame tables; a guard may also lie in the fit-mode function and its tables, the two calculators or the crop function
                "lcd32dsq_fx3_v1": (((0x1DF6A8, 0x1DF6B0), (0x1DF700, 0x1DF718), (0x1DF7B8, 0x1DF7C0), (0x5FAF34, 0x5FAF38), (0x5FAF68, 0x5FAF6C),
                                     (0xD2E510, 0xD2E588), (0xD2E588, 0xD2E600), (0xD2E600, 0xD2E678)),
                                    ((0x1DF458, 0x1DF4EC), (0x1DF680, 0x1DF884), (0x5FAF04, 0x5FAFF6)))}


def words_header(name="outsz2560_fx3_v1"):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    assert d["kind"] == "ram_words"
    sites = [(int(s["ram_address"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])) for s in d["sites"]]
    guards = [(int(g["ram_address"], 16), bytes.fromhex(g["bytes"])) for g in d["guards"]]
    site_regions, guard_only = WORD_REGIONS[name]
    within = lambda a, n, regions: any(lo <= a and a + n <= hi for lo, hi in regions)
    inside = lambda a, n: within(a, n, site_regions)
    assert sites and all(len(o) == len(n) == 4 and o != n and a % 4 == 0 and inside(a, 4) for a, o, n in sites)
    assert guards and all(0 < len(b) <= 16 and within(a, len(b), site_regions + guard_only) for a, b in guards)
    if "artifact_sha256" in d:                           # a design of words inside the loaded image: every byte is the file's
        image = (EX / "nflasha8/cpapp-b.bin").read_bytes()
        assert d["artifact_sha256"] == hashlib.sha256(image).hexdigest()
        assert all(image[a - BASE:a - BASE + 4] == o for a, o, _ in sites) and all(image[a - BASE:a - BASE + len(b)] == b for a, b in guards)
    if "dmmcfg_sha256" in d:                             # a design of words in the run-time copy of DmmCfg.bin: every byte is the file's
        cfg = (EX / "nflasha8/DmmCfg.bin").read_bytes()
        assert d["dmmcfg_sha256"] == hashlib.sha256(cfg).hexdigest() and "artifact_sha256" not in d
        for a, old, e in [(a, o, s) for (a, o, _), s in zip(sites, d["sites"])] + [(a, b, g) for (a, b), g in zip(guards, d["guards"])]:
            f = int(e["file_offset"], 16)
            assert cfg[f:f + len(old)] == old and (a - DMM_UNITS[0]) % 0x14 + len(old) <= 0x14, "not the file's bytes, or across two records"
        assert len({a for a, _, _ in sites}) == len(sites)
    assert not any(a < sa + 4 and sa < a + len(b) for a, b in guards for sa, _, _ in sites), "a guard overlaps a site"
    out = [f"/* Generated by helper_fx3/gen_fx3_write.py from modding/designs/{name}.json (FX3 7.02). Do not edit. */",
           "/* Words of the coprocessor's RAM tables (cpapp-b.bin 7.02): %d site(s), %d guard(s). */" % (len(sites), len(guards)),
           '#define WORDS_DESIGN "%s"' % name,
           "struct ram_word { u32 address; u8 stock[4]; u8 changed[4]; };",
           "static const struct ram_word ram_words[] = {"]
    out += ["    { 0x%x, { %s }, { %s } }," % (a, hx(o), hx(n)) for a, o, n in sites]
    out += ["};", "/* bytes beside the sites that must be as listed before anything is written */",
            "struct ram_guard { u32 address; u32 len; u8 bytes[16]; };", "static const struct ram_guard ram_guards[] = {"]
    out += ["    { 0x%x, %d, { %s } }," % (a, len(b), hx(b.ljust(16, b"\0"))) for a, b in guards]
    out += ["};"]
    (OUT / f"expected_words_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(sites), len(guards)


def mp_header(name="ogfile2560_hs_s_fx3_v1"):
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    av, lm = (EX / "nflasha3/av-cam.bin").read_bytes(), (EX / "nflasha15/lib/libmpr.so").read_bytes()
    assert d["artifact_sha256"] == {"libmpr.so": hashlib.sha256(lm).hexdigest(), "av-cam.bin": hashlib.sha256(av).hexdigest()}
    # 2026-11-25 (ogfile2560_hs_s_fx3_v2): as helper/gen_expected.py for the A7 IV's ogfile2560_hs_s_v2, a code site is allowed only in libmpr.so and
    # only where the design names it in libmpr_code_guards, with the instructions around it as guards (build_ogfile.py checks them by disassembly)
    code_ok = {int(g["site"], 16): g["guards"] for g in d.get("libmpr_code_guards", [])}
    assert all(not p["code"] or (p["binary"] == "libmpr.so" and int(p["file_off"], 16) in code_ok) for p in d["patches"]), \
        "not a data-only encoder-side design (a code site must be in libmpr.so and named in libmpr_code_guards)"
    tabs = {"av-cam.bin": [], "libmpr.so": []}
    for p in d["patches"]:
        off, old, new = int(p["file_off"], 16), bytes.fromhex(p["old"]), bytes.fromhex(p["new"])
        data = av if p["binary"] == "av-cam.bin" else lm
        assert len(old) == len(new) <= 16 and old != new and data[off:off + len(old)] == old
        tabs[p["binary"]].append((off, 1, old, new))
    # guards, as gen_expected.py --mp: the 4K row of the unit-type table, clip-format row 5, each changed descriptor's profile key
    g_av = [(UNIT + 0x20, av[UNIT + 0x20:UNIT + 0x30]), (CLIP + 0x50, av[CLIP + 0x50:CLIP + 0x60])]
    assert struct.unpack("<4I", g_av[0][1]) == (0x486, 0x474, 0x477, 0x47A) and struct.unpack("<4I", g_av[1][1]) == (1, 3840, 2160, 23)
    for x in d["descriptors"]:
        o = DESC + x["descriptor"] * 0x90 + 0x28
        assert struct.unpack_from("<I", av, o)[0] == x["profile_key"]
        g_av.append((o, av[o:o + 4]))
    g_lm = [(0, lm[:16])]
    for off, _, old, new in tabs["libmpr.so"]:
        if off in code_ok:                                       # a named code site: its guards are the instructions the design lists
            for g in code_ok[off]:
                a, b = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
                assert lm[a:a + len(b)] == b and len(b) <= 16
                g_lm.append((a, b))
            continue
        if len(old) == 4:                                        # width and height of a g_videoParamComb row (the 4224x2816 designs): the codec word before
            assert (off - 4 - COMB) % 0x18 == 0 and struct.unpack("<HH", old) == (3840, 2160)
            g_lm.append((off - 4, lm[off - 4:off]))
            continue
        assert (off - 6 - COMB) % 0x18 == 0 and struct.unpack_from("<H", lm, off - 2)[0] == 3840
        g_lm.append((off - 6, lm[off - 6:off]))
    for binary, guards in (("av-cam.bin", g_av), ("libmpr.so", g_lm)):
        sites = tabs[binary]
        assert not any(a < s + len(o) and s < a + len(b) for a, b in guards for s, _, o, _ in sites), "a guard overlaps a site"
        tabs[binary] = sorted(sites + [(a, 0, b, b"") for a, b in guards])
        assert all(tabs[binary][k][0] + len(tabs[binary][k][2]) <= tabs[binary][k + 1][0] for k in range(len(tabs[binary]) - 1)), "entries overlap"
    first = tabs["av-cam.bin"][0][0] & ~0xFFF
    last = max(a + len(o) for a, _, o, _ in tabs["av-cam.bin"])
    span = ((last - first) + 0xFFF) & ~0xFFF
    assert 0x392000 <= first and first + span <= 0x3DB000, "an av-cam.bin site lies outside the pages of its tables"
    phoff, phentsize, phnum = struct.unpack_from("<Q", lm, 0x20)[0], *struct.unpack_from("<HH", lm, 0x36)
    load0 = next(struct.unpack_from("<IIQQQQQQ", lm, phoff + k * phentsize) for k in range(phnum) if struct.unpack_from("<I", lm, phoff + k * phentsize)[0] == 1)
    assert load0[2] == 0 and load0[3] == 0 and max(a + len(o) for a, _, o, _ in tabs["libmpr.so"]) <= load0[5], "a libmpr.so site lies outside the first segment"
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    out = [f"/* Generated by helper_fx3/gen_fx3_write.py from modding/designs/{name}.json (FX3 7.02). Do not edit. */",
           "/* av-cam.bin %s..., libmpr.so %s... (7.02). kind 1: a site of the design; kind 0: a guard, bytes that must be as in the file. */"
           % (d["artifact_sha256"]["av-cam.bin"][:16], d["artifact_sha256"]["libmpr.so"][:16]),
           '#define MP_DESIGN "%s"' % name,
           "#define MP_AV_FIRST 0x%xUL                 /* file offset of the first page read of av-cam.bin */" % first,
           "#define MP_AV_BYTES 0x%xUL                  /* whole pages: every entry of mp_av lies inside */" % span,
           "struct mp_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };"]
    longest = max(len(tabs["av-cam.bin"]), len(tabs["libmpr.so"]))
    if longest > 96:
        out.insert(-1, "#define MP_MAX %d                          /* room for the entries of the longer table (levels 19 and 20) */" % ((longest + 31) & ~31))
    for binary, var in (("av-cam.bin", "mp_av"), ("libmpr.so", "mp_lm")):
        out.append("static const struct mp_site %s[] = {      /* %s: file offsets */" % (var, binary))
        out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in tabs[binary]]
        out.append("};")
    (OUT / f"expected_mp_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return {b: (sum(1 for e in t if e[1] == 1), sum(1 for e in t if e[1] == 0)) for b, t in tabs.items()}, hex(first), hex(span)


AD_KVA, AD_ALIGN = 0xFFFFFFC001000000, 0x200000      # av-cam.bin's run address (file offset + this); the code page's alias rule (readcheck.c level 29)


def ad_header(name="avdec8k_fx3_v1"):
    """Levels 29 and 30 (2026-11-25): code and data sites of av-cam.bin. The code sites are instructions of kernel text, so the checks are
    stricter than level 19's: every code site is one aligned instruction word in ONE page, and the whole page is carried, so that the helper
    can require every other byte of it to be as in the file. The data entries (one row of the decode size table and its guards) lie in one
    other page."""
    d = json.loads((DES / f"{name}.json").read_text(encoding="utf8"))
    av = (EX / "nflasha3/av-cam.bin").read_bytes()
    assert d["kind"] == "avcam_code_data" and d["artifact_sha256"] == hashlib.sha256(av).hexdigest()
    assert int(d["kernel_va_base"], 16) == AD_KVA and int(d["avcam_phys"], 16) == 0x401000000
    code_page, data_page = int(d["code_page"], 16), int(d["data_page"], 16)
    assert code_page % 0x1000 == 0 and data_page % 0x1000 == 0 and code_page != data_page
    assert code_page + 0x1000 <= DATA_LO <= data_page, "the code page must lie in av-cam.bin's text, the data page in its data"
    code = []
    for s in d["code_sites"]:
        off, old, new = int(s["file_off"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])
        assert off % 4 == 0 and len(old) == len(new) == 4 and old != new and off & ~0xFFF == code_page and av[off:off + 4] == old
        code.append((off, 1, old, new))
    data = []
    for s in d["data_sites"]:
        off, old, new = int(s["file_off"], 16), bytes.fromhex(s["old"]), bytes.fromhex(s["new"])
        assert off % 4 == 0 and len(old) == len(new) == 4 and old != new and off & ~0xFFF == data_page and av[off:off + 4] == old
        data.append((off, 1, old, new))
    for g in d["data_guards"]:
        off, b = int(g["file_off"], 16), bytes.fromhex(g["bytes"])
        assert 0 < len(b) <= 16 and off & ~0xFFF == (off + len(b) - 1) & ~0xFFF == data_page and av[off:off + len(b)] == b
        data.append((off, 0, b, b""))
    code.sort(), data.sort()
    for t in (code, data):
        assert all(t[k][0] + len(t[k][2]) <= t[k + 1][0] for k in range(len(t) - 1)), "entries overlap"
    assert len(code) <= 16 and len(data) <= 16
    page = av[code_page:code_page + 0x1000]
    h16 = lambda b: hx(b.ljust(16, b"\0"))
    out = [f"/* Generated by helper_fx3/gen_fx3_write.py from modding/designs/{name}.json (FX3 7.02). Do not edit. */",
           "/* av-cam.bin %s...: %d code sites in page %#x (kernel text), %d data entries in page %#x. kind 1: a site; kind 0: a guard. */"
           % (d["artifact_sha256"][:16], len(code), code_page, len(data), data_page),
           '#define AD_DESIGN "%s"' % name,
           "#define AD_KVA 0x%xUL          /* av-cam.bin's run address: kernel address = file offset + this */" % AD_KVA,
           "#define AD_CODE_PAGE 0x%xUL" % code_page,
           "#define AD_DATA_PAGE 0x%xUL" % data_page,
           "#define AD_ALIGN 0x%xUL                 /* the code page is mapped at the kernel address's offset from a boundary of this size */" % AD_ALIGN,
           "struct ad_site { u32 off; u8 len; u8 kind; u8 stock[16]; u8 changed[16]; };",
           "static const struct ad_site ad_code[] = {      /* file offsets; instruction words */"]
    out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in code]
    out += ["};", "static const struct ad_site ad_data[] = {      /* file offsets */"]
    out += ["    { 0x%x, %d, %d, { %s }, { %s } }," % (a, len(o), kind, h16(o), h16(n)) for a, kind, o, n in data]
    out += ["};", "static const u8 ad_code_file[4096] = {      /* the code page as in the file: every byte but the sites must hold this */"]
    out += ["    %s," % hx(page[k:k + 16]) for k in range(0, 0x1000, 16)]
    out += ["};"]
    (OUT / f"expected_ad_{name}.h").write_text("\n".join(out) + "\n", encoding="utf8", newline="\n")
    return len(code), len(data), hashlib.sha256(page).hexdigest()[:16]


